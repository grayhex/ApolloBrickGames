/**
 * Мелодии «Морского боя» — расшифровка звука видео владельца (25 октября 2026): заставка при включении, музыка «Ромео и Джульетты» и звук анимации игры A.
 * Высоты сняты спектральным разбором (пик + параболическая интерполяция) и привязаны к равномерно темперированному строю с поправкой устройства +12 центов (звукоряд — ми мажор);
 * на 3-й гармонике пищалки (резонанс около 2 кГц) частота сворачивается к основному тону. Длительности — по видео (точность ±5 мс), петли замкнуты на длину записи.
 * Формат шага: `[Гц, мс]`; `0` — пауза, отрицательное число — шум вокруг `|Гц|` («рябь» и всплески). Нативного повтора у `BrickAudio` нет, поэтому петля разворачивается в длинный массив.
 */
type Step = readonly [number, number];

const toTones = (steps: readonly Step[]): BrickTone[] =>
  steps.map(([hz, ms]): BrickTone => (hz < 0 ? { hz: -hz, ms, noise: true } : { hz, ms }));

/** Повторить петлю `times` раз (примерно столько минут звука, сколько нужно, пока игрок смотрит на экран). */
const repeat = (steps: readonly Step[], times: number, head: readonly Step[] = []): BrickTone[] => toTones([...head, ...Array.from({ length: times }, () => steps).flat()]);

