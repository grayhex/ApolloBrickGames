import type { AudioCue } from './audio';

/**
 * Звуки устройства, восстановленные по записи со звуком (Video_Project_6.mp4, методика — docs/video-observations.md §8).
 * Всё звучит на одном «пищалке»: прямоугольные волны, до двух голосов; все высоты — ноты одного лада от основного тона.
 * Что измерено, а что допущено, помечено у каждой фразы.
 */

/** Основной тон лада (нота «до»), Гц: кластер 762 Гц в записи; остальные ноты — равномерно-темперированные полутона от него. */
export const ROOT_HZ = 762;

/** Полутоны от основного тона → Гц. */
export const semitoneHz = (semitones: number): number => ROOT_HZ * 2 ** (semitones / 12);

/** Доля мелодии, мс: сетка по аккордам двух заходов (такт ≈ 0,5425 с ≈ 110 уд/мин). */
export const STEP_MS = 135.6;

/** Короткая «нота» эффектов, мс: ровно 1/5 доли (прыжок — семь таких нот, фанфара — по две). */
export const MICRO_MS = STEP_MS / 5;

/** Звучит одна нота или пауза. */
export interface Note {
  ms: number;
  /** Частоты голосов, Гц (до двух одновременно); пусто — пауза. */
  hz: readonly number[];
  /** Плавный переход частоты первого голоса к этой к концу ноты. */
  glideTo?: number;
  /** Шум: частота случайно прыгает в пределах [lo, hi] Гц каждые `hop` мс. */
  noise?: { lo: number; hi: number; hop: number };
  /** Тишина в конце ноты (артикуляция), мс; входит в `ms`. */
  gap?: number;
}

const tone = (ms: number, ...semitones: number[]): Note => ({ ms, hz: semitones.map(semitoneHz) });
const rest = (ms: number): Note => ({ ms, hz: [] });
const glide = (ms: number, fromHz: number, toHz: number): Note => ({ ms, hz: [fromHz], glideTo: toHz });
const noise = (ms: number, lo = 500, hi = 5000, hop = 4): Note => ({ ms, hz: [], noise: { lo, hi, hop } });

// ── Мелодия ──────────────────────────────────────────────────────────────────

/** Названия нот лада → полутоны от основного тона: A — нижняя ля, C — основной тон, `a` — верхняя ля. */
const PITCH: Readonly<Record<string, number>> = { A: -3, B: -1, C: 0, D: 2, E: 4, F: 5, G: 7, a: 9 };

/**
 * Игровая мелодия: 20 тактов по 4 доли; каждая доля — набор нот, звучащих вместе (`CE` — аккорд до + ми).
 * Доли 0–77 (такты 0–19, до середины последнего) **измерены** по двум заходам записи: такты 0–10 слышны чисто (заход 2),
 * такты 11–19 — из обоих заходов (стрельба поверх мелодии, шумы вычтены сравнением). Две последние доли такта 19 (`C D`)
 * **допущены**: запись обрывается на 78-й доле. Граница цикла в записи не видна, поэтому мелодия зациклена по такту.
 */
const TUNE_BARS: readonly string[] = [
  'CE CE C D',
  'CE CE C D',
  'CE CE D D',
  'CE CE C D',
  'CE CE C D',
  'CE CE C D',
  'CE CE D D',
  'CD CD C C',
  'CD CD C C',
  'D D C C',
  'CD CD CE CE',
  'C C A C',
  'C C A C',
  'C C A C',
  'C C D D',
  'C C C D',
  'CE CE C D',
  'CE CE C D',
  'CE CE D D',
  'CE CE C D',
];

/** Длина мелодии в долях. */
export const TUNE_STEPS = TUNE_BARS.length * 4;

/**
 * Доли → ноты. Нота длится не дольше двух долей: меняется набор тонов либо наступает чётная доля — по этому правилу
 * светодиод в записи переключается на каждой новой ноте (совпадение 92 % долей). В конце каждой ноты — короткая пауза.
 */
function tuneNotes(): Note[] {
  const steps = TUNE_BARS.flatMap((bar) => bar.split(' '));
  const notes: Note[] = [];
  let previous = '';
  steps.forEach((token, index) => {
    const last = notes[notes.length - 1];
    if (last && token === previous && index % 2 === 1) {
      notes[notes.length - 1] = { ...last, ms: last.ms + STEP_MS };
    } else {
      notes.push({ ms: STEP_MS, hz: [...token].map((letter) => semitoneHz(PITCH[letter] ?? 0)), gap: 12 });
    }
    previous = token;
  });
  return notes;
}

export const TUNE: readonly Note[] = tuneNotes();

/**
 * Фанфара запуска: 12 нот по 2/5 доли (≈ 53,5 мс) — «ми ре ми ре до ре ми ре ми ля си до»: **измерено** (записано 9,147–9,789 с).
 * Светодиоды бегут по нотам. После фанфары — доля тишины и мелодия.
 */
export const FANFARE: readonly Note[] = [4, 2, 4, 2, 0, 2, 4, 2, 4, 9, 11, 12].map((semitones) => tone(MICRO_MS * 2, semitones));

/**
 * Тон готовности после гибели: нота «ре» на 8 долей (≈ 1,09 с), светодиоды красный → жёлтый → зелёный на 2 + 3 + 3 доли.
 * **Измерено** (34,735–35,813 с); деление на три части — по смене светодиодов.
 */
export const READY: readonly Note[] = [2, 3, 3].map((steps) => tone(STEP_MS * steps, 2));

// ── Эффекты ──────────────────────────────────────────────────────────────────

export interface CueDef {
  notes: readonly Note[];
  /** Приоритет в канале эффектов: слабый не перебивает звучащий сильный. */
  priority: number;
  /** Задержка от события движка до первого звука, мс. */
  delayMs?: number;
  /** Громкость относительно остальных эффектов (по умолчанию 1). */
  gain?: number;
}

/** Серия из 12 шумовых «пачек» по 40 мс через 65 мс — грохот после падения (32,57–33,33 с). */
const crash: Note[] = Array.from({ length: 12 }, () => [noise(40, 600, 1000, 3), rest(25)]).flat();

/** Мелодичный джингл гибели: 8 нот в такт долям (ми ми ми ля ми ми ля ля) поверх «до» — измерено (33,45–34,50 с). */
const jingle: Note[] = [4, 4, 4, 9, 4, 4, 9, 9].flatMap((semitones) => [
  { ...tone(STEP_MS - 36, semitones, 0) },
  rest(36),
]);

/**
 * Эффекты. Источник — запись (docs/video-observations.md §8); `условный` — в записи нет, оставлен прежний сигнал демо.
 * Смещения (`delayMs`) подобраны так, чтобы при событиях движка звук ложился на то же место, что и в записи.
 */
export const CUES: Readonly<Record<AudioCue, CueDef>> = {
  /** Шаг построения комнаты при интро: падающий свип 3000 → 1550 Гц за 32 мс и щелчок; 17 тиков с периодом 149 мс — измерено. */
  introStep: { priority: 1, notes: [glide(32, 3000, 1550), tone(10, 17)] },
  /** Прыжок: «лесенка» до-ре-ми-фа-соль-фа-ми по 27 мс (0, 2, 4, 5, 7, 5, 4 полутона) — измерено (три прыжка). */
  jump: { priority: 2, notes: [0, 2, 4, 5, 7, 5, 4].map((semitones) => tone(MICRO_MS, semitones)) },
  /** Удар головой: восходящий свип ≈ 700 → 2800 Гц за 150 мс, пауза, треск; в записи звучит через 0,25 с после начала прыжка — измерено. */
  bump: {
    priority: 2,
    delayMs: 100,
    notes: [glide(150, 700, 2800), rest(80), ...[807, 855, 807, 855, 906].map((hz) => ({ ms: 13, hz: [hz] }))],
  },
  /** Приземление: «ми ля си ми ля си» (4, −3, −1, 4, −3, −1 полутона) — измерено после прыжков в яме. */
  land: {
    priority: 1,
    notes: [tone(40, 4), tone(25, -3), tone(25, -1), tone(45, 4), tone(25, -3), tone(25, -1)],
  },
  /**
   * Разрушение перекрытия: 10 шумовых всплесков по 115 мс через 180 мс (≈ 1,8 с) вместо свипа третьего удара — измерено.
   * Приоритет низкий (допущение): следующий прыжок или выстрел игрока обрывает грохот, а не глохнет на 1,8 с.
   */
  crumble: {
    priority: 1,
    delayMs: 50,
    gain: 0.6,
    notes: Array.from({ length: 10 }, () => [noise(115), rest(65)]).flat(),
  },
  /** Выстрел: быстрый падающий свип 3800 → 1800 Гц за 32 мс (при удержании FIRE в записи — каждые 83 мс) — измерено. */
  shot: { priority: 1, notes: [glide(32, 3800, 1800)] },
  /** Гибель: падение (свип 1700 → 800 Гц за 240 мс), пауза, грохот, пауза, джингл — измерено (32,12–34,53 с). */
  death: {
    priority: 4,
    notes: [glide(240, 1700, 800), rest(210), ...crash, rest(120), ...jingle],
  },
  /** Выключение: один щелчок (36,70 с) — измерено. */
  powerOff: { priority: 5, notes: [noise(8, 500, 5000, 2)] },
  /** Подтверждение переключателя «Звук» — условный. */
  confirm: { priority: 2, notes: [{ ms: 45, hz: [1047] }, { ms: 70, hz: [1568] }] },
  /** Попадание по мишени — условный (в записи звук попадания не выделен). */
  hit: { priority: 2, notes: [{ ms: 45, hz: [660] }, rest(20), { ms: 60, hz: [660] }] },
  /** Снаряд упёрся в препятствие — условный. */
  blocked: { priority: 0, notes: [{ ms: 30, hz: [330] }] },
  /** Конец игры (последний участок пройден) — условный. Переход на следующий участок в записи беззвучен: мелодия идёт до смены экрана. */
  levelCompleted: {
    priority: 4,
    notes: [523, 659, 784].map((hz) => ({ ms: 80, hz: [hz] })).concat([{ ms: 180, hz: [1047] }]),
  },
  /** Наступили на врага — условный (в записи нет): короткий восходящий «прыг» и щелчок. */
  stomp: { priority: 3, notes: [glide(60, 600, 1400), tone(35, 12)] },
  /** Секрет с 200 жизнями сработал — условный (в записи нет): восходящее арпеджио «до ми соль до» и повтор верхних нот. */
  secret: {
    priority: 3,
    notes: [0, 4, 7, 12, 7, 12].map((semitones, index) => tone(index < 4 ? 70 : 90, semitones)),
  },
  /** Игра окончена — условный (в записи нет). */
  gameOver: {
    priority: 4,
    notes: [392, 330, 262].map((hz) => ({ ms: 130, hz: [hz] })).concat([{ ms: 320, hz: [196] }]),
  },
};

/** Длина эффекта, мс (с задержкой). */
export function cueDurationMs(cue: AudioCue): number {
  const def = CUES[cue];
  return (def.delayMs ?? 0) + def.notes.reduce((sum, note) => sum + note.ms, 0);
}
