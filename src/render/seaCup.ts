/** Контуры значка как один путь для `fill('evenodd')`, смещённый на `(x, y)` (по умолчанию — на место на панели). */
export function seaCupPath(x: number = SEA_CUP.x, y: number = SEA_CUP.y): Path2D {
  const path = new Path2D();
  for (const contour of SEA_CUP.contours) {
    for (let i = 0; i < contour.length; i += 2) {
      const px = x + (contour[i] ?? 0) / 10;
      const py = y + (contour[i + 1] ?? 0) / 10;
      if (i === 0) path.moveTo(px, py);
      else path.lineTo(px, py);
    }
    path.closePath();
  }
  return path;
}
