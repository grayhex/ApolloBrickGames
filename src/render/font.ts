export const FONT_WIDTH = 3;
export const FONT_HEIGHT = 5;
const ADVANCE = FONT_WIDTH + 1;

export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * ADVANCE - 1;
}

/** Рисует текст пикселями 1×1 логический пиксель. Незнакомые символы — пробел. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, ink: string): void {
  ctx.fillStyle = ink;
  let cursor = x;
  for (const char of text.toUpperCase()) {
    const rows = FONT[char] ?? FONT[' '] ?? [];
    rows.forEach((row, py) => {
      for (let px = 0; px < FONT_WIDTH; px++) {
        if (row[px] === '#') ctx.fillRect(cursor + px, y + py, 1, 1);
      }
    });
    cursor += ADVANCE;
  }
}
