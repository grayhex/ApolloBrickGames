/** Двузначный номер варианта: две мелкие цифры. */
function drawMode(field: Uint8Array, mode: number): void {
  const tens = Math.floor(mode / 10) % 10;
  const units = mode % 10;
  const t = SMALL_DIGITS[tens];
  const u = SMALL_DIGITS[units];
  if (t) blit(field, t, MENU_LAYOUT.modeTens.x, MENU_LAYOUT.modeTens.y, CELL_ON);
  if (u) blit(field, u, MENU_LAYOUT.modeUnits.x, MENU_LAYOUT.modeUnits.y, CELL_ON);
}

/** Крупный знак игры: цифра `0`–`9` или буква `A`–`F`; незнакомый символ не рисуется. */
export function symbolSprite(symbol: string): Sprite | null {
  if (/^[0-9]$/.test(symbol)) return BIG_DIGITS[Number(symbol)] ?? null;
  return BIG_LETTERS[symbol.toUpperCase()] ?? null;
}

/**
 * Экран меню: знак игры (цифра или буква), номер варианта (с единицы, «01»), иллюстрация игры `illustrationId`.
 */
export function menuField(symbol: string, modeNumber: number, illustrationId: string): Uint8Array {
  const field = emptyField();
  const big = symbolSprite(symbol);
  if (big) blit(field, big, MENU_LAYOUT.gameDigit.x, MENU_LAYOUT.gameDigit.y, CELL_ON);
  else if (/^\d{2}$/.test(symbol)) {
    blit(field, BIG_DIGITS[Number(symbol[0])]!, 1, 0);
    blit(field, BIG_DIGITS[Number(symbol[1])]!, 6, 0);
  }
  drawMode(field, modeNumber);
  const art = ILLUSTRATIONS[illustrationId];
  if (art) {
    const picture = pictureField(art, 0, MENU_LAYOUT.illustrationTop);
    for (let i = 0; i < picture.length; i++) if (picture[i]) field[i] = picture[i] ?? 0;
  }
  return field;
}
